--
-- Name: v_order_tracking; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_order_tracking AS
 SELECT o.id AS order_id,
    o.order_number,
    o.user_id,
    o.status AS order_status,
    o.placed_at,
    s.id AS shipment_id,
    s.carrier,
    s.tracking_number,
    s.status AS shipment_status,
    s.estimated_delivery,
    s.delay_reason,
    e.description AS last_event,
    e.location AS last_location,
    e.occurred_at AS last_event_at
   FROM ((public.orders o
     LEFT JOIN public.shipments s ON ((s.order_id = o.id)))
     LEFT JOIN LATERAL ( SELECT shipment_events.description,
            shipment_events.location,
            shipment_events.occurred_at
           FROM public.shipment_events
          WHERE (shipment_events.shipment_id = s.id)
          ORDER BY shipment_events.occurred_at DESC
         LIMIT 1) e ON (true));


--
-- Name: v_product_availability; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_product_availability AS
 SELECT p.id AS product_id,
    p.sku,
    (COALESCE(sum((i.quantity_on_hand - i.quantity_reserved)), (0)::bigint))::integer AS available_qty,
        CASE
            WHEN (COALESCE(sum((i.quantity_on_hand - i.quantity_reserved)), (0)::bigint) <= 0) THEN 'OUT_OF_STOCK'::text
            WHEN (COALESCE(sum((i.quantity_on_hand - i.quantity_reserved)), (0)::bigint) <= 10) THEN 'LOW_STOCK'::text
            ELSE 'IN_STOCK'::text
        END AS availability
   FROM (public.products p
     LEFT JOIN public.inventory i ON ((i.product_id = p.id)))
  GROUP BY p.id, p.sku;


--
-- Name: v_sales_velocity; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_sales_velocity AS
 SELECT i.product_id,
    i.warehouse_id,
    i.quantity_on_hand,
    COALESCE(s.units_30d, (0)::bigint) AS units_sold_30d,
    round(((COALESCE(s.units_30d, (0)::bigint))::numeric / 30.0), 2) AS avg_daily_sales,
        CASE
            WHEN (COALESCE(s.units_30d, (0)::bigint) = 0) THEN NULL::numeric
            ELSE round(((i.quantity_on_hand)::numeric / ((s.units_30d)::numeric / 30.0)), 1)
        END AS days_of_cover
   FROM (public.inventory i
     LEFT JOIN ( SELECT inventory_movements.product_id,
            inventory_movements.warehouse_id,
            sum((- inventory_movements.change_qty)) AS units_30d
           FROM public.inventory_movements
          WHERE (((inventory_movements.reason)::text = 'SALE'::text) AND (inventory_movements.created_at >= (now() - '30 days'::interval)))
          GROUP BY inventory_movements.product_id, inventory_movements.warehouse_id) s ON (((s.product_id = i.product_id) AND (s.warehouse_id = i.warehouse_id))));


