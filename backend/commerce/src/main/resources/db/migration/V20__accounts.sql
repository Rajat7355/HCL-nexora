CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            CITEXT       NOT NULL UNIQUE,
    password         VARCHAR(128) NOT NULL,                 -- Django hash
    first_name       VARCHAR(100) NOT NULL DEFAULT '',
    last_name        VARCHAR(100) NOT NULL DEFAULT '',
    membership_tier  VARCHAR(10)  NOT NULL DEFAULT 'BASIC'
                     CHECK (membership_tier IN ('BASIC','PRIME','PREMIUM')),
    region           VARCHAR(16)  NOT NULL DEFAULT 'GLOBAL', -- used to filter KB documents
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
    is_staff         BOOLEAN      NOT NULL DEFAULT FALSE,
    is_superuser     BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login       TIMESTAMPTZ,
    date_joined      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    full_name    VARCHAR(150) NOT NULL,
    phone        VARCHAR(30),
    line1        VARCHAR(255) NOT NULL,
    line2        VARCHAR(255),
    city         VARCHAR(100) NOT NULL,
    state        VARCHAR(100),
    postal_code  VARCHAR(20)  NOT NULL,
    country      VARCHAR(2)   NOT NULL,                      -- ISO 3166-1 alpha-2
    is_default   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_addresses_user ON addresses(user_id);

CREATE UNIQUE INDEX uq_addresses_one_default ON addresses(user_id) WHERE is_default;

CREATE TABLE user_preferred_categories (
    user_id      BIGINT NOT NULL REFERENCES users(id)      ON DELETE CASCADE,
    category_id  BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, category_id)
);

CREATE TABLE user_preferred_brands (
    user_id   BIGINT NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
    brand_id  BIGINT NOT NULL REFERENCES brands(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, brand_id)
);

CREATE TABLE customer_preferences (
    user_id              BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    budget_min           NUMERIC(12,2) CHECK (budget_min >= 0),
    budget_max           NUMERIC(12,2) CHECK (budget_max >= 0),
    preferred_currency   CHAR(3)       NOT NULL DEFAULT 'USD',
    delivery_preference  VARCHAR(20)   NOT NULL DEFAULT 'STANDARD'
                         CHECK (delivery_preference IN ('STANDARD','EXPRESS')),
    notes                TEXT          NOT NULL DEFAULT '',
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_budget_range CHECK (budget_min IS NULL OR budget_max IS NULL OR budget_min <= budget_max)
);
