CREATE TABLE carts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cart_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id     BIGINT      NOT NULL REFERENCES carts(id)    ON DELETE CASCADE,
    product_id  BIGINT      NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    quantity    INT         NOT NULL CHECK (quantity > 0),
    added_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cart_product UNIQUE (cart_id, product_id)
);

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(20)   NOT NULL UNIQUE,            -- shown to customers, e.g. SS-100042
    user_id          BIGINT        NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PLACED'
                     CHECK (status IN ('PLACED','CONFIRMED','PACKED','SHIPPED','OUT_FOR_DELIVERY',
                                       'DELIVERED','CANCELLED','RETURN_REQUESTED','RETURNED')),
    subtotal         NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    shipping_fee     NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
    discount         NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    total            NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    currency         CHAR(3)       NOT NULL DEFAULT 'USD',
    shipping_address JSONB         NOT NULL,                   -- snapshot at order time
    warehouse_id     BIGINT        REFERENCES warehouses(id) ON DELETE SET NULL,
    placed_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    cancelled_at     TIMESTAMPTZ,
    CONSTRAINT chk_order_total CHECK (total = subtotal + shipping_fee - discount)
);

CREATE INDEX idx_orders_user_time ON orders(user_id, placed_at DESC);

CREATE INDEX idx_orders_status    ON orders(status, updated_at);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT        NOT NULL REFERENCES orders(id)   ON DELETE CASCADE,
    product_id    BIGINT        NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    product_name  VARCHAR(255)  NOT NULL,                      -- snapshot
    unit_price    NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    quantity      INT           NOT NULL CHECK (quantity > 0),
    line_total    NUMERIC(12,2) GENERATED ALWAYS AS (unit_price * quantity) STORED
);

CREATE INDEX idx_order_items_order   ON order_items(order_id);

CREATE INDEX idx_order_items_product ON order_items(product_id);

CREATE TABLE shipments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT       NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    warehouse_id        BIGINT       REFERENCES warehouses(id) ON DELETE SET NULL,
    carrier             VARCHAR(60)  NOT NULL,
    tracking_number     VARCHAR(60)  NOT NULL UNIQUE,
    status              VARCHAR(20)  NOT NULL DEFAULT 'LABEL_CREATED'
                        CHECK (status IN ('LABEL_CREATED','PICKED_UP','IN_TRANSIT','OUT_FOR_DELIVERY',
                                          'DELIVERED','DELAYED','EXCEPTION')),
    shipped_at          TIMESTAMPTZ,
    estimated_delivery  DATE,
    delivered_at        TIMESTAMPTZ,
    delay_reason        TEXT
);

CREATE INDEX idx_shipments_order  ON shipments(order_id);

CREATE INDEX idx_shipments_status ON shipments(status);

CREATE TABLE shipment_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id  BIGINT       NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
    status       VARCHAR(20)  NOT NULL,
    location     VARCHAR(150),
    description  VARCHAR(255) NOT NULL,
    occurred_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    is_mock      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_shipment_events_shipment_time ON shipment_events(shipment_id, occurred_at DESC);

-- One row per shipment with its latest event. Read-only input for the order-tracking
-- tool and the fulfilment agent (Aman).
CREATE VIEW v_order_tracking AS
SELECT o.id            AS order_id,
       o.order_number,
       o.user_id,
       o.status        AS order_status,
       o.placed_at,
       s.id            AS shipment_id,
       s.carrier,
       s.tracking_number,
       s.status        AS shipment_status,
       s.estimated_delivery,
       s.delay_reason,
       e.description   AS last_event,
       e.location      AS last_location,
       e.occurred_at   AS last_event_at
FROM orders o
LEFT JOIN shipments s ON s.order_id = o.id
LEFT JOIN LATERAL (
    SELECT description, location, occurred_at
    FROM shipment_events
    WHERE shipment_id = s.id
    ORDER BY occurred_at DESC
    LIMIT 1
) e ON TRUE;
