CREATE TABLE ai_decision_logs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    session_id         UUID,                                   -- chat session id; plain column, no FK, so files stay independent
    task_type          VARCHAR(30) NOT NULL
                       CHECK (task_type IN ('SHOPPING_RECOMMENDATION','RAG_ANSWER','ORDER_TRACKING',
                                            'INTENT_ROUTING','AGENT_DECISION')),
    input_text         TEXT        NOT NULL,
    interpreted        JSONB,                                  -- extracted requirements / routed intent
    retrieved_context  JSONB,                                  -- product ids or chunk ids + scores
    output             JSONB,                                  -- final structured response
    confidence         VARCHAR(6)  CHECK (confidence IN ('HIGH','MEDIUM','LOW')),
    status             VARCHAR(10) NOT NULL DEFAULT 'OK' CHECK (status IN ('OK','REFUSED','ERROR')),
    error_message      TEXT,
    model_name         VARCHAR(100),
    prompt_tokens      INT,
    completion_tokens  INT,
    latency_ms         INT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_ai_logs_task_time ON ai_decision_logs(task_type, created_at DESC);

CREATE INDEX idx_ai_logs_user      ON ai_decision_logs(user_id, created_at DESC);
