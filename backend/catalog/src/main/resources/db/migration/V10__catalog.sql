CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       REFERENCES categories(id) ON DELETE RESTRICT,
    name        VARCHAR(120) NOT NULL,
    slug        VARCHAR(140) NOT NULL UNIQUE,
    description TEXT         NOT NULL DEFAULT '',
    sort_order  INT          NOT NULL DEFAULT 0,
    CONSTRAINT chk_category_not_self_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX idx_categories_parent ON categories(parent_id);

CREATE TABLE brands (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(120) NOT NULL UNIQUE,
    slug  VARCHAR(140) NOT NULL UNIQUE
);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           VARCHAR(32)   NOT NULL UNIQUE,              -- public productId, e.g. LAP101
    name          VARCHAR(255)  NOT NULL,
    brand_id      BIGINT        NOT NULL REFERENCES brands(id)     ON DELETE RESTRICT,
    category_id   BIGINT        NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    description   TEXT          NOT NULL DEFAULT '',
    price         NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    currency      CHAR(3)       NOT NULL DEFAULT 'USD',
    rating        NUMERIC(2,1)  NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
    rating_count  INT           NOT NULL DEFAULT 0 CHECK (rating_count >= 0),
    specs         JSONB         NOT NULL DEFAULT '{}'::jsonb,  -- {"ram_gb":16,"cpu":"Intel i7","storage":"512GB SSD"}
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    search_vector TSVECTOR GENERATED ALWAYS AS (
                      setweight(to_tsvector('english', coalesce(name, '')), 'A') ||
                      setweight(to_tsvector('english', coalesce(description, '')), 'B')
                  ) STORED,
    embedding     vector(384),                                -- semantic product search / recommendation
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_products_category   ON products(category_id) WHERE is_active;

CREATE INDEX idx_products_brand      ON products(brand_id);

CREATE INDEX idx_products_price      ON products(price);

CREATE INDEX idx_products_rating     ON products(rating DESC);

CREATE INDEX idx_products_search     ON products USING gin (search_vector);

CREATE INDEX idx_products_specs      ON products USING gin (specs jsonb_path_ops);

CREATE INDEX idx_products_name_trgm  ON products USING gin (name gin_trgm_ops);

CREATE INDEX idx_products_embedding  ON products USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);

CREATE TABLE product_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    url         VARCHAR(500) NOT NULL,
    alt_text    VARCHAR(255) NOT NULL DEFAULT '',
    sort_order  INT          NOT NULL DEFAULT 0,
    is_primary  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_product_images_product ON product_images(product_id);

CREATE UNIQUE INDEX uq_product_one_primary_image ON product_images(product_id) WHERE is_primary;
