CREATE TABLE warehouses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(16)  NOT NULL UNIQUE,
    name       VARCHAR(150) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    country    VARCHAR(2)   NOT NULL,
    region     VARCHAR(16)  NOT NULL DEFAULT 'GLOBAL',
    is_active  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE inventory (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT      NOT NULL REFERENCES products(id)   ON DELETE CASCADE,
    warehouse_id      BIGINT      NOT NULL REFERENCES warehouses(id) ON DELETE CASCADE,
    quantity_on_hand  INT         NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    quantity_reserved INT         NOT NULL DEFAULT 0 CHECK (quantity_reserved >= 0),
    reorder_level     INT         NOT NULL DEFAULT 10 CHECK (reorder_level >= 0),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_inventory_product_warehouse UNIQUE (product_id, warehouse_id),
    CONSTRAINT chk_reserved_le_on_hand CHECK (quantity_reserved <= quantity_on_hand)
);

CREATE INDEX idx_inventory_warehouse ON inventory(warehouse_id);

CREATE TABLE inventory_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT      NOT NULL REFERENCES products(id)   ON DELETE CASCADE,
    warehouse_id  BIGINT      NOT NULL REFERENCES warehouses(id) ON DELETE CASCADE,
    change_qty    INT         NOT NULL CHECK (change_qty <> 0),
    reason        VARCHAR(20) NOT NULL
                  CHECK (reason IN ('SALE','RESTOCK','RETURN','TRANSFER_IN','TRANSFER_OUT','ADJUSTMENT')),
    order_id      BIGINT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_inv_mov_product_time ON inventory_movements(product_id, created_at DESC);

CREATE VIEW v_product_availability AS
SELECT p.id AS product_id,
       p.sku,
       COALESCE(SUM(i.quantity_on_hand - i.quantity_reserved), 0)::INT AS available_qty,
       CASE
           WHEN COALESCE(SUM(i.quantity_on_hand - i.quantity_reserved), 0) <= 0  THEN 'OUT_OF_STOCK'
           WHEN COALESCE(SUM(i.quantity_on_hand - i.quantity_reserved), 0) <= 10 THEN 'LOW_STOCK'
           ELSE 'IN_STOCK'
       END AS availability
FROM products p
LEFT JOIN inventory i ON i.product_id = p.id
GROUP BY p.id, p.sku;

-- Sales velocity and days of cover: read-only input for the inventory agent (Aman)
CREATE VIEW v_sales_velocity AS
SELECT i.product_id,
       i.warehouse_id,
       i.quantity_on_hand,
       COALESCE(s.units_30d, 0)                                   AS units_sold_30d,
       ROUND(COALESCE(s.units_30d, 0) / 30.0, 2)                  AS avg_daily_sales,
       CASE WHEN COALESCE(s.units_30d, 0) = 0 THEN NULL
            ELSE ROUND(i.quantity_on_hand / (s.units_30d / 30.0), 1) END AS days_of_cover
FROM inventory i
LEFT JOIN (
    SELECT product_id, warehouse_id, SUM(-change_qty) AS units_30d
    FROM inventory_movements
    WHERE reason = 'SALE' AND created_at >= now() - INTERVAL '30 days'
    GROUP BY product_id, warehouse_id
) s ON s.product_id = i.product_id AND s.warehouse_id = i.warehouse_id;
