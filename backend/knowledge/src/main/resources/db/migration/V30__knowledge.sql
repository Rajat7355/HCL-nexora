CREATE TABLE kb_documents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(255) NOT NULL,
    category          VARCHAR(30)  NOT NULL
                      CHECK (category IN ('RETURN','SHIPPING','REFUND','WARRANTY','MEMBERSHIP',
                                          'PRODUCT_MANUAL','SELLER_GUIDELINE','DELIVERY_SLA')),
    region            VARCHAR(16)  NOT NULL DEFAULT 'GLOBAL',
    version           VARCHAR(20)  NOT NULL,                   -- e.g. 2026.1
    effective_date    DATE         NOT NULL,
    expiry_date       DATE,
    source_type       VARCHAR(10)  NOT NULL CHECK (source_type IN ('PDF','MARKDOWN','JSON')),
    original_filename VARCHAR(255) NOT NULL,
    file_path         VARCHAR(500) NOT NULL,
    checksum_sha256   CHAR(64)     NOT NULL,
    product_id        BIGINT       REFERENCES products(id) ON DELETE SET NULL,  -- for product manuals / warranty
    status            VARCHAR(12)  NOT NULL DEFAULT 'PROCESSING'
                      CHECK (status IN ('PROCESSING','APPROVED','SUPERSEDED','FAILED')),
    chunk_count       INT          NOT NULL DEFAULT 0,
    error_message     TEXT,
    uploaded_by       BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_kb_title_version_region UNIQUE (title, version, region),
    CONSTRAINT chk_kb_dates CHECK (expiry_date IS NULL OR expiry_date > effective_date)
);

CREATE INDEX idx_kb_docs_active ON kb_documents(category, region, effective_date) WHERE status = 'APPROVED';

CREATE TABLE kb_chunks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT       NOT NULL REFERENCES kb_documents(id) ON DELETE CASCADE,
    chunk_index  INT          NOT NULL CHECK (chunk_index >= 0),
    section      VARCHAR(255) NOT NULL DEFAULT '',             -- heading, cited in sources[]
    content      TEXT         NOT NULL,
    token_count  INT          NOT NULL DEFAULT 0,
    metadata     JSONB        NOT NULL DEFAULT '{}'::jsonb,    -- page number, json path, etc.
    embedding    vector(384)  NOT NULL,
    content_tsv  TSVECTOR GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
    CONSTRAINT uq_chunk_doc_index UNIQUE (document_id, chunk_index)
);

CREATE INDEX idx_kb_chunks_document  ON kb_chunks(document_id);

CREATE INDEX idx_kb_chunks_tsv       ON kb_chunks USING gin (content_tsv);

CREATE INDEX idx_kb_chunks_embedding ON kb_chunks USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);
