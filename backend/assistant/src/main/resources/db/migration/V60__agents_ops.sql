CREATE TABLE agent_runs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_type         VARCHAR(20) NOT NULL CHECK (agent_type IN ('INVENTORY','FULFILLMENT','SUPPORT_TRIAGE')),
    trigger_type       VARCHAR(10) NOT NULL DEFAULT 'MANUAL' CHECK (trigger_type IN ('SCHEDULED','MANUAL','EVENT')),
    goal               TEXT        NOT NULL,
    status             VARCHAR(20) NOT NULL DEFAULT 'RUNNING'
                       CHECK (status IN ('RUNNING','COMPLETED','FAILED','AWAITING_APPROVAL','REJECTED')),
    result_summary     TEXT,
    requires_approval  BOOLEAN     NOT NULL DEFAULT FALSE,
    approved_by        BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    approved_at        TIMESTAMPTZ,
    started_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at        TIMESTAMPTZ
);

CREATE INDEX idx_agent_runs_type_time ON agent_runs(agent_type, started_at DESC);

CREATE TABLE agent_steps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT      NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
    step_no       INT         NOT NULL CHECK (step_no > 0),
    tool_name     VARCHAR(60) NOT NULL,
    reasoning     TEXT,
    tool_input    JSONB       NOT NULL DEFAULT '{}'::jsonb,
    tool_output   JSONB,
    status        VARCHAR(10) NOT NULL DEFAULT 'OK' CHECK (status IN ('OK','ERROR')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_agent_step UNIQUE (run_id, step_no)
);

CREATE TABLE stock_alerts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id              BIGINT      NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    warehouse_id            BIGINT      REFERENCES warehouses(id) ON DELETE CASCADE,
    severity                VARCHAR(8)  NOT NULL CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    days_of_cover           NUMERIC(6,1),
    predicted_stockout_date DATE,
    recommended_action      TEXT        NOT NULL,
    status                  VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED')),
    agent_run_id            BIGINT      REFERENCES agent_runs(id) ON DELETE SET NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at             TIMESTAMPTZ
);

CREATE INDEX idx_stock_alerts_open ON stock_alerts(severity, created_at DESC) WHERE status <> 'RESOLVED';

CREATE TABLE support_tickets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       REFERENCES users(id)  ON DELETE SET NULL,
    order_id      BIGINT       REFERENCES orders(id) ON DELETE SET NULL,
    subject       VARCHAR(255) NOT NULL,
    description   TEXT         NOT NULL,
    category      VARCHAR(20)  NOT NULL DEFAULT 'OTHER'
                  CHECK (category IN ('DELIVERY','RETURN_REFUND','PRODUCT','ACCOUNT','OTHER')),
    priority      VARCHAR(8)   NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')),
    team          VARCHAR(10)  NOT NULL DEFAULT 'SUPPORT' CHECK (team IN ('SUPPORT','LOGISTICS')),
    status        VARCHAR(12)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED')),
    assigned_to   BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    agent_run_id  BIGINT       REFERENCES agent_runs(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolved_at   TIMESTAMPTZ
);

CREATE INDEX idx_tickets_queue ON support_tickets(team, status, priority);
